/**
 * Математика калькулятора підлоги.
 *
 * Винесена з компонента сторінки товару окремо, щоб формулу можна було
 * перевіряти тестами без рендера всієї сторінки — і щоб початкові
 * значення та перерахунок гарантовано рахувалися ОДНИМ кодом. Раніше
 * початкова площа була вписана числом (14.4 м² для кімнати 4.0 × 3.2,
 * тобто 12.8), і до першого перерахунку картка показувала неправду.
 *
 * ФОРМУЛА:
 *   площа       = довжина × ширина, округлено до 0.1 м²
 *   упаковки    = ceil(площа / місткість упаковки)
 *   сума        = округлена площа × ціна за м²
 *
 * Чому сума рахується від ОКРУГЛЕНОЇ площі: інакше три рядки результату
 * не сходяться між собою — користувач бачить «8.9 м²» і суму, яку
 * неможливо отримати множенням цих двох чисел. Самоузгодженість
 * важливіша за десяті частки гривні.
 *
 * ЗАПАС НА ПІДРІЗ тут НЕ додається: калькулятор рахує чисту площу
 * кімнати. Округлення вгору до цілої упаковки дає природний невеликий
 * буфер, але це не заміна галузевого запасу 5–10%. Якщо такий запас
 * потрібен — це рішення про бізнес-логіку, і його треба вводити свідомо
 * (окремим полем у налаштуваннях калькулятора), а не ховати у формулу.
 */

/** Приводить введене значення до невід'ємного числа */
export function toPositiveNumber(value) {
  const parsed = parseFloat(value);
  if (!Number.isFinite(parsed) || parsed < 0) return 0;
  return parsed;
}

export function calculateFloor(length, width, pricePerM2, packCapacity) {
  /* Від'ємні розміри кімнати не існують. Без цієї нормалізації «-5 × 3»
     давало «-15 м², -6 упаковок, -57 750 грн» — числа, які виглядають
     як робочий результат, але є безглуздими. */
  const safeLength = toPositiveNumber(length);
  const safeWidth = toPositiveNumber(width);

  /* Місткість упаковки нулем бути не може: ділення дало б Infinity */
  const capacity = Number.isFinite(packCapacity) && packCapacity > 0 ? packCapacity : 1;
  const price = Number.isFinite(pricePerM2) && pricePerM2 > 0 ? pricePerM2 : 0;

  const area = parseFloat((safeLength * safeWidth).toFixed(1));
  const packages = Math.ceil(area / capacity);
  const totalPrice = Math.round(area * price);

  return { area, packages, totalPrice };
}

export default calculateFloor;
